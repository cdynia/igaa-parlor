/* IGAA Parlor service worker — offline app shell */
const CACHE = "igaa-parlor-v1";
const ASSETS = [
  "./",
  "index.html",
  "IGAA-Beginner.html",
  "IGAA-Advanced.html",
  "Times-Up-Jr.html",
  "manifest.webmanifest",
  "icon-192.png",
  "icon-512.png",
  "apple-touch-icon.png"
];

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  const sameOrigin = url.origin === self.location.origin;

  // Same-origin: cache-first, fall back to network, then to cached index for navigations.
  if (sameOrigin) {
    e.respondWith(
      caches.match(req).then((hit) =>
        hit ||
        fetch(req).then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
          return res;
        }).catch(() =>
          req.mode === "navigate" ? caches.match("index.html") : undefined
        )
      )
    );
    return;
  }

  // Cross-origin (e.g. Google Fonts): network-first, cache opportunistically, fall back to cache.
  e.respondWith(
    fetch(req).then((res) => {
      const copy = res.clone();
      caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
      return res;
    }).catch(() => caches.match(req))
  );
});
